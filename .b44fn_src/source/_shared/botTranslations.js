const LANG_NAMES = {
  en: 'English', zh: '中文', es: 'Español', hi: 'हिन्दी', ar: 'العربية',
  fr: 'Français', ru: 'Русский', pt: 'Português', de: 'Deutsch', bn: 'বাংলা',
};

// Translate a key for a given language, with optional params.
// Checks the core table first, then the flow tables (A/B/C), then English.
const FLOW_TABLES = [TA, TB, TC, TD, TE, TF, TG];
export function t(lang, key, params) {
  let str = (T[lang] && T[lang][key]);
  if (str === undefined) {
    for (const F of FLOW_TABLES) {
      str = (F[lang] && F[lang][key]) || F.en[key];
      if (str !== undefined) break;
    }
  }
  if (str === undefined) str = key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
  }
  return str;
}

export function langName(code) {
  return LANG_NAMES[code] || code;
}

// Build the reply keyboard for a given language.
// opts.hidePremium / opts.hideStars remove those buttons when true.
export function buildReplyKeyboard(lang, opts) {
  const L = lang || 'en';
  const o = opts || {};
  const keyboard = [
    [{ text: t(L, 'menu.buy') }, { text: t(L, 'menu.topup') }],
    [{ text: t(L, 'menu.sell') }, { text: t(L, 'menu.withdraw') }],
    [{ text: t(L, 'menu.myaccount') }],
  ];
  keyboard.push([{ text: t(L, 'menu.channel') }, { text: t(L, 'menu.support') }]);
  keyboard.push([{ text: t(L, 'menu.language') }, { text: t(L, 'menu.refer') }]);
  return { keyboard, resize_keyboard: true };
}

// Build a comprehensive map of ALL translated button texts → action key.
// This lets us route button presses regardless of the user's language.
export function buildAllReplyActions() {
  const actions = {};
  const keys = ['buy', 'topup', 'sell', 'myaccount', 'rewards', 'withdraw', 'premium', 'stars', 'channel', 'support', 'language', 'refer'];
  for (const lang of Object.keys(T)) {
    for (const k of keys) {
      const menuKey = k === 'rewards' ? 'menu.reward' : `menu.${k}`;
      const btnText = t(lang, menuKey);
      if (btnText) actions[btnText] = k;
    }
  }
  // Telegram keeps showing the LAST reply keyboard a chat received, so old
  // chats still display pre-rename buttons. Their presses must keep working:
  // legacy 'Buy' labels route to the same Market action as the new one.
  const LEGACY_LABELS = {
    'buy': ['🌍 Buy', '🌍 কিনুন', '🌍 Comprar', '🌍 Acheter', '🌍 Kaufen', '🌍 Купить', '🌍 شراء', '🌍 खरीदें', '🌍 购买'],
  };
  for (const [action, labels] of Object.entries(LEGACY_LABELS)) {
    for (const label of labels) {
      if (!actions[label]) actions[label] = action;
    }
  }
  return actions;
}