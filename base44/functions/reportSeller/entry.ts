import { runSql, sqlString } from "../../shared/supabase.ts";
import { resolveIdentity } from "../../shared/telegram.ts";

const SCAM_TYPES = ["not_delivered", "invalid_account", "scam", "price_manipulation", "other"];

// Stores a seller report from the marketplace. The reporter must be a real
// Telegram user — initData is verified against the bot token — and the report
// lands in the Supabase seller_reports table for admin review.
export default async function(req) {
  try {
    const body = await req.json().catch(() => ({}));
    if (!body.initData) {
      return Response.json({ error: "Open the app from Telegram to report a seller" }, { status: 401 });
    }
    const identity = await resolveIdentity(body.initData);

    const sellerUsername = String(body.seller_username || "").trim().replace(/^@+/, "").slice(0, 64);
    const sellerId = String(body.seller_id || "").trim().slice(0, 64);
    const scamType = String(body.scam_type || "");
    const details = String(body.details || "").trim().slice(0, 1000);

    if (!sellerUsername) {
      return Response.json({ error: "Seller username is required" }, { status: 400 });
    }
    if (!SCAM_TYPES.includes(scamType)) {
      return Response.json({ error: "Invalid scam type" }, { status: 400 });
    }

    // Idempotent bootstrap — a no-op once the table exists.
    await runSql(
      `create table if not exists seller_reports (
        id bigint generated by default as identity primary key,
        reporter_email text not null,
        seller_username text not null,
        seller_id text,
        scam_type text not null,
        details text,
        status text not null default 'pending',
        created_date timestamptz not null default now()
      )`
    );

    await runSql(
      `insert into seller_reports (reporter_email, seller_username, seller_id, scam_type, details)
       values (${sqlString(identity.identity_email)}, ${sqlString(sellerUsername)}, ${sqlString(sellerId || null)}, ${sqlString(scamType)}, ${sqlString(details || null)})`
    );

    return Response.json({ ok: true });
  } catch (error) {
    return Response.json({ error: error.message }, { status: 400 });
  }
}