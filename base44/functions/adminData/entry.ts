import { runSql } from "../../shared/supabase.ts";
import { resolveIdentity } from "../../shared/telegram.ts";

// Admin-only dashboard data: seller reports, pending withdrawals and the
// global purchase / sale / top-up / withdrawal histories. Every user-facing
// list joins tg_web_users so rows carry the Telegram username for display.
export default async function(req) {
  try {
    const body = await req.json().catch(() => ({}));
    const identity = await resolveIdentity(body.initData || "");
    if (identity.role !== "admin") {
      return Response.json({ error: "Admin access required" }, { status: 403 });
    }

    // Idempotent bootstrap — a no-op once the table exists (reportSeller also
    // creates it, but the admin page may open first).
    await runSql(
      `create table if not exists seller_reports (
        id bigint generated by default as identity primary key,
        reporter_email text not null,
        seller_username text not null,
        seller_id text,
        scam_type text not null,
        details text,
        status text not null default 'pending',
        created_date timestamptz not null default now()
      )`
    );

    const [reports, pendingWithdrawals, purchases, sales, topups, withdrawals, userCount] = await Promise.all([
      runSql(
        `select count(*)::int as count from tg_web_users`
      ),
      runSql(
        `select id, reporter_email, seller_username, seller_id, scam_type, details, status, created_date
         from seller_reports order by created_date desc limit 100`
      ),
      runSql(
        `select w.id, w.amount, w.coin, w.network, w.wallet_address, w.status, w.user_email, w.created_date,
                u.telegram_username
         from withdrawals w
         left join tg_web_users u on u.identity_email = w.user_email
         where w.status not in ('approved', 'rejected')
         order by w.created_date desc limit 100`
      ),
      runSql(
        `select o.id, o.product_name, o.price, o.status, o.user_email, o.created_date, u.telegram_username
         from product_orders o
         left join tg_web_users u on u.identity_email = o.user_email
         order by o.created_date desc limit 50`
      ),
      runSql(
        `select s.id, s.country_iso, s.phone_number, s.reward_amount, s.status, s.user_email, s.created_date,
                u.telegram_username
         from session_requests s
         left join tg_web_users u on u.identity_email = s.user_email
         order by s.created_date desc limit 50`
      ),
      runSql(
        `select t.id, t.amount, t.network, t.status, t.user_email, t.created_date, u.telegram_username
         from top_ups t
         left join tg_web_users u on u.identity_email = t.user_email
         where t.network <> 'purchase_commission'
         order by t.created_date desc limit 50`
      ),
      runSql(
        `select w.id, w.amount, w.network, w.status, w.user_email, w.created_date, u.telegram_username
         from withdrawals w
         left join tg_web_users u on u.identity_email = w.user_email
         order by w.created_date desc limit 50`
      ),
    ]);

    return Response.json({
      reports,
      users_count: Number(userCount && userCount[0] ? userCount[0].count : 0) || 0,
      pending_withdrawals: pendingWithdrawals.map((w) => ({ ...w, amount: Number(w.amount) })),
      purchases: purchases.map((o) => ({ ...o, price: Number(o.price) })),
      sales: sales.map((s) => ({ ...s, reward_amount: s.reward_amount === null ? null : Number(s.reward_amount) })),
      topups: topups.map((x) => ({ ...x, amount: Number(x.amount) })),
      withdrawals: withdrawals.map((w) => ({ ...w, amount: Number(w.amount) })),
    });
  } catch (error) {
    return Response.json({ error: error.message }, { status: 400 });
  }
}